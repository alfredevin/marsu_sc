<script>
    document.addEventListener("DOMContentLoaded", function () {
        // 1. Dropdown Chevron Rotate Behavior
        const progBtn = document.getElementById("programDropdownBtn");
        const progArrow = document.getElementById("appointmentDropdownArrow");
        const progDropdown = progBtn ? progBtn.closest(".dropdown") : null;

        if (progDropdown && progArrow) {
            progDropdown.addEventListener("show.bs.dropdown", function () {
                progArrow.style.transform = "rotate(180deg)";
            });
            progDropdown.addEventListener("hidden.bs.dropdown", function () {
                progArrow.style.transform = "rotate(0deg)";
            });
        }

        // 2. Program Filtering
        const programMenuItems = document.querySelectorAll("#appointmentProgramMenu .dropdown-item");
        const selectedProgramText = document.getElementById("selectedProgramText");
        const rows = document.querySelectorAll("#appointmentTableBody tr.appointment-row");
        const noMatch = document.getElementById("noMatchAppointment");
        const searchInput = document.getElementById("appointmentSearchInput");

        function applyFilterAndSearch() {
            const selectedProg = selectedProgramText.textContent.trim();
            const query = searchInput.value.toLowerCase().trim();
            let visibleCount = 0;

            rows.forEach(row => {
                const rowProg = row.getAttribute("data-program") || "";
                const rowText = row.innerText.toLowerCase();

                const matchesProgram = (selectedProg === "All Programs" || rowProg === selectedProg);
                const matchesSearch = (query === "" || rowText.includes(query));

                if (matchesProgram && matchesSearch) {
                    row.style.display = "";
                    visibleCount++;
                } else {
                    row.style.display = "none";
                }
            });

            if (noMatch) {
                if (visibleCount === 0) {
                    noMatch.classList.remove("d-none");
                } else {
                    noMatch.classList.add("d-none");
                }
            }
        }

        programMenuItems.forEach(item => {
            item.addEventListener("click", function (e) {
                e.preventDefault();
                programMenuItems.forEach(i => i.classList.remove("active"));
                this.classList.add("active");
                selectedProgramText.textContent = this.textContent.trim();
                applyFilterAndSearch();
            });
        });

        if (searchInput) {
            searchInput.addEventListener("input", applyFilterAndSearch);
        }

        // 3. View Button Data Population
        let currentRecord = {};
        const viewButtons = document.querySelectorAll(".btn-view-appointment");
        const dossierModal = new bootstrap.Modal(document.getElementById("modal-appointment-detail"));
        const scheduleModal = new bootstrap.Modal(document.getElementById("modal-schedule-session"));

        viewButtons.forEach(btn => {
            btn.addEventListener("click", function () {
                currentRecord = {
                    id: this.getAttribute("data-id") || "APT-2026-001",
                    name: this.getAttribute("data-name") || "Student Appointee",
                    date: this.getAttribute("data-date") || "2026-10-21",
                    program: this.getAttribute("data-program") || "BSIS",
                    year: this.getAttribute("data-year") || "1st Year",
                    referral: this.getAttribute("data-referral") || "Self-Referral",
                    concern: this.getAttribute("data-concern") || "Counseling Inquiry",
                    status: this.getAttribute("data-status") || "Pending Review"
                };

                // I-populate ang Intake Slip Dossier Modal
                document.getElementById("dossierStudentName").textContent = currentRecord.name;
                document.getElementById("dossierApptId").textContent = currentRecord.id;
                document.getElementById("dossierDate").textContent = currentRecord.date;
                document.getElementById("dossierProgram").textContent = currentRecord.program;
                document.getElementById("dossierReferral").textContent = currentRecord.referral;
                document.getElementById("dossierStatusBadge").textContent = currentRecord.status;

                dossierModal.show();
            });
        });

        // 4. Pag-click ng "Schedule Session" sa loob ng Intake Slip
        const btnOpenScheduleModal = document.getElementById("btnOpenScheduleModal");
        if (btnOpenScheduleModal) {
            btnOpenScheduleModal.addEventListener("click", function () {
                // Isara ang Intake Form modal
                dossierModal.hide();

                // I-populate ang Scheduling Modal gamit ang napiling student info
                document.getElementById("schedStudentName").textContent = currentRecord.name || "DELA CRUZ, JUAN L.";
                document.getElementById("schedApptId").textContent = currentRecord.id || "APT-2026-001";
                document.getElementById("schedProgram").textContent = currentRecord.program || "BSIS";
                document.getElementById("inputSchedConcern").value = currentRecord.concern || "Academic / Performance Concerns";

                // Buksan ang Schedule Guidance Session modal
                setTimeout(() => {
                    scheduleModal.show();
                }, 300);
            });
        }

        // 5. Back to Intake Slip button mula sa Scheduling Modal
        const btnBackToDossier = document.getElementById("btnBackToDossier");
        if (btnBackToDossier) {
            btnBackToDossier.addEventListener("click", function () {
                scheduleModal.hide();
                setTimeout(() => {
                    dossierModal.show();
                }, 300);
            });
        }

        // 6. Confirm and Connect to Calendar Session
        const btnConfirmSchedule = document.getElementById("btnConfirmSchedule");
        if (btnConfirmSchedule) {
            btnConfirmSchedule.addEventListener("click", function () {
                const schedDate = document.getElementById("inputSchedDate").value;
                const schedTime = document.getElementById("inputSchedTime").value;
                const schedRoom = document.getElementById("inputSchedRoom").value;
                const schedCounselor = document.getElementById("inputSchedCounselor").value;

                if (!schedDate || !schedTime) {
                    alert("Paki-pili ang petsa at oras ng counseling session.");
                    return;
                }

                // Mock saving session to storage / state
                const scheduledSessionData = {
                    appointmentId: currentRecord.id,
                    studentName: currentRecord.name,
                    program: currentRecord.program,
                    date: schedDate,
                    time: schedTime,
                    room: schedRoom,
                    counselor: schedCounselor,
                    concern: currentRecord.concern,
                    status: "Confirmed"
                };

                // I-save pansamantala sa localStorage para ma-access ng session calendar
                try {
                    localStorage.setItem("lastScheduledSession", JSON.stringify(scheduledSessionData));
                } catch (e) { }

                scheduleModal.hide();

                // Notipikasyon at opsyon na pumunta sa Session Calendar
                const goToCalendar = confirm(
                    "Matagumpay na naitakda ang Guidance Session!\n\n" +
                    "Appointee: " + currentRecord.name + "\n" +
                    "Petsa: " + schedDate + "\n" +
                    "Oras: " + schedTime + "\n" +
                    "Silid: " + schedRoom + "\n\n" +
                    "Nais mo bang pumunta agad sa Session Calendar upang makita ang bagong schedule?"
                );

                if (goToCalendar) {
                    window.location.href = "session_calendar.php";
                }
            });
        }
    });
</script>